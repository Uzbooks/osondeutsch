/* OsonTillar service worker: sayt bir marta ochilgach, internetsiz ham ishlaydi.
   Yangilanish chiqqanda VERSION ni oʻzgartiring. */
const VERSION = "osontillar-v3";
const FILES = ["./", "index.html", "config.js", "manifest.webmanifest", "privacy.html", "icons/icon-192.png", "icons/icon-512.png"];
self.addEventListener("install", e => { e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
/* Network first (always fresh when online), cache as fallback (offline). Third-party requests are left alone. */
self.addEventListener("fetch", e => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  e.respondWith(fetch(e.request).then(r => { const copy = r.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); return r; })
    .catch(() => caches.match(e.request).then(r => r || caches.match("index.html"))));
});
